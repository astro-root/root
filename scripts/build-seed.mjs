// seed/ のMarkdownから db/seed.sql を生成する。INSERT OR IGNORE なので、
// すでに管理画面で編集した内容は上書きしない（再実行しても安全）。
import fs from 'node:fs';
import path from 'node:path';
import matter from 'gray-matter';

const root = path.resolve(import.meta.dirname, '..');
const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const iso = (d) => (d ? new Date(d).toISOString() : null);
const isPlaceholder = (u) => !u || /^https?:\/\/(example\.com|github\.com\/?|x\.com\/?)(\/|$)/i.test(u) && (/example\.com/.test(u) || /^https?:\/\/(github\.com|x\.com)\/?$/.test(u));

const out = ['-- generated by scripts/build-seed.mjs (INSERT OR IGNORE)'];
const read = (dir) => fs.readdirSync(path.join(root, 'seed', dir)).filter((f) => f.endsWith('.md')).sort()
  .map((f) => ({ slug: f.replace(/\.md$/, ''), ...matter(fs.readFileSync(path.join(root, 'seed', dir, f), 'utf8')) }));

for (const { slug, data, content } of read('content/projects')) {
  const year = String(data.year ?? '');
  const y = year.match(/\d{4}/)?.[0];
  out.push(`INSERT OR IGNORE INTO projects (id,title,summary,body_md,category,status,year,technology,url,github,featured,sort_order,state,published_at) VALUES (${[
    q(slug), q(data.title), q(data.summary ?? ''), q(content.trim()), q(data.category ?? ''), q(data.status ?? 'Active'), q(year),
    q(JSON.stringify(data.technology ?? [])), q(isPlaceholder(data.url) ? null : data.url), q(isPlaceholder(data.github) ? null : data.github),
    data.featured ? 1 : 0, Number(data.order ?? 99), q('published'), q(y ? `${y}-01-01T00:00:00.000Z` : null)
  ].join(',')});`);
}

for (const { slug, data, content } of read('content/blog')) {
  out.push(`INSERT OR IGNORE INTO posts (slug,title,excerpt,body_md,category,tags,state,published_at) VALUES (${[
    q(slug), q(data.title), q(data.excerpt ?? ''), q(content.trim()), q(data.category ?? ''), q(JSON.stringify(data.tags ?? [])),
    q(data.published === false ? 'draft' : 'published'), q(iso(data.date))
  ].join(',')});`);
}

const about = matter(fs.readFileSync(path.join(root, 'seed/content/about/index.md'), 'utf8'));
const aboutMeta = { displayName: 'Root', status: 'Student / Developer / Quiz Player', based: 'Japan', image: '', imageAlt: '' };
out.push(`INSERT OR IGNORE INTO pages (slug,title,description,body_md,meta) VALUES (${[
  q('about'), q('About'), q('るーとについて。'), q(about.content.trim()), q(JSON.stringify(aboutMeta))
].join(',')});`);

for (const slug of ['terms', 'privacy']) {
  const m = matter(fs.readFileSync(path.join(root, 'seed/legal', `${slug}.md`), 'utf8'));
  out.push(`INSERT OR IGNORE INTO pages (slug,title,description,body_md) VALUES (${[q(slug), q(m.data.title), q(m.data.description), q(m.content.trim())].join(',')});`);
}

fs.mkdirSync(path.join(root, 'db'), { recursive: true });
fs.writeFileSync(path.join(root, 'db/seed.sql'), out.join('\n') + '\n');
console.log(`db/seed.sql を生成しました（${out.length - 1} 文）`);
